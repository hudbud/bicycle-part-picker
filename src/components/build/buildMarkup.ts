/**
 * Forum / Reddit markup for a build — PCPartPicker's "Markup" feature.
 * Pure functions (no React), so exports and dialogs can share them.
 */

export type MarkupFormat = 'reddit' | 'bbcode' | 'text'

export const MARKUP_FORMATS: { id: MarkupFormat; label: string }[] = [
  { id: 'reddit', label: 'Reddit' },
  { id: 'bbcode', label: 'BBCode' },
  { id: 'text', label: 'Text' },
]

export interface MarkupOptions {
  /** Link back to this build (the share URL). */
  permalink?: string
  /** Site origin used for product links; defaults to window.location.origin. */
  origin?: string
  /** Defaults to now. */
  date?: Date
  compat?: BuildCompat
}

/** One-line compatibility summary, e.g. "1 problem, 2 warnings" or "No issues or incompatibilities found". */
export function compatSummary(build: Build, compat: BuildCompat = computeCompat(build)): string {
  const level = compatLevel(build, compat)
  if (level === 'empty') return 'No parts selected'
  if (level === 'ok') return 'No issues or incompatibilities found'
  const bits: string[] = []
  if (compat.errors.length) bits.push(`${compat.errors.length} problem${compat.errors.length === 1 ? '' : 's'}`)
  if (compat.warnings.length) bits.push(`${compat.warnings.length} warning${compat.warnings.length === 1 ? '' : 's'}`)
  return bits.join(', ')
}

function stamp(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}

function priceWhere(row: SlotRow): string {
  if (row.price == null) return '—'
  return row.offer ? `${formatPrice(row.price)} @ ${row.offer.merchant.name}` : formatPrice(row.price)
}

const qtyPrefix = (row: SlotRow) => (row.quantity > 1 ? `${row.quantity} × ` : '')

export function generateMarkup(build: Build, format: MarkupFormat, opts: MarkupOptions = {}): string {
  const origin = opts.origin ?? (typeof window !== 'undefined' ? window.location.origin : '')
  const compat = opts.compat ?? computeCompat(build)
  const rows = getSlotRows(build, compat, true)
  const extras = build.additionalItems ?? []
  const totals = getBuildTotals(build)
  const approx = totals.missingPrices > 0 ? '~' : ''
  const total = `${approx}${formatPrice(totals.total)}`
  const compatLine = `Compatibility: ${compatSummary(build, compat)}`
  const weightLine = `Estimated Weight: ${weightLabel(compat)}`
  const when = stamp(opts.date ?? new Date())
  const productUrl = (row: SlotRow) => (row.part && !row.isCustom ? `${origin}${productPath(row.part.id)}` : row.part?.url)

  if (format === 'reddit') {
    const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/([[\]])/g, '\\$1')
    const lines: string[] = []
    lines.push(opts.permalink ? `[Pedal Parts Picker Part List](${opts.permalink})` : `**${esc(build.name)}**`, '')
    lines.push('Type|Item|Weight|Price', ':----|:----|:----|:----')
    for (const row of rows) {
      const name = esc(partTitle(row.part!))
      const url = productUrl(row)
      const item = `${qtyPrefix(row)}${url ? `[${name}](${url})` : name}${row.isCustom ? ' *(custom)*' : ''}`
      lines.push(`**${row.label}** | ${item} | ${row.weightG != null ? formatWeight(row.weightG) : '—'} | ${priceWhere(row)}`)
    }
    for (const x of extras) {
      lines.push(`**Extra** | ${x.url ? `[${esc(x.name)}](${x.url})` : esc(x.name)} | | ${formatPrice(x.price)}`)
    }
    lines.push(' | *Prices include shipping and discounts* | |')
    lines.push(` | **Total** | **${weightLabel(compat)}** | **${total}**`)
    lines.push(` | ${compatLine} | |`)
    lines.push(` | Generated by [Pedal Parts Picker](${origin}) ${when} | |`)
    return lines.join('\n')
  }

  if (format === 'bbcode') {
    const lines: string[] = []
    lines.push(opts.permalink ? `[url=${opts.permalink}]Pedal Parts Picker Part List[/url]` : `[b]${build.name}[/b]`, '')
    for (const row of rows) {
      const name = partTitle(row.part!)
      const url = productUrl(row)
      lines.push(`[b]${row.label}:[/b] ${qtyPrefix(row)}${url ? `[url=${url}]${name}[/url]` : name}${row.isCustom ? ' (custom)' : ''}  (${priceWhere(row)})`)
    }
    for (const x of extras) {
      lines.push(`[b]Extra:[/b] ${x.url ? `[url=${x.url}]${x.name}[/url]` : x.name}  (${formatPrice(x.price)})`)
    }
    lines.push(`[i]Prices include shipping and discounts[/i]`)
    lines.push(`[b]Total:[/b] ${total}`)
    lines.push(`[b]${weightLine}[/b]`)
    lines.push(compatLine)
    lines.push(`[i]Generated by [url=${origin}]Pedal Parts Picker[/url] ${when}[/i]`)
    return lines.join('\n')
  }

  const lines: string[] = []
  lines.push(opts.permalink ? `Pedal Parts Picker Part List: ${opts.permalink}` : build.name, '')
  for (const row of rows) {
    lines.push(`${row.label}: ${qtyPrefix(row)}${partTitle(row.part!)}${row.isCustom ? ' (custom)' : ''}  (${priceWhere(row)})`)
  }
  for (const x of extras) lines.push(`Extra: ${x.name}  (${formatPrice(x.price)})`)
  lines.push('Prices include shipping and discounts')
  lines.push(`Total: ${total}`)
  lines.push(weightLine)
  lines.push(compatLine)
  lines.push(`Generated by Pedal Parts Picker ${when}`)
  return lines.join('\n')
}

// ---------------------------------------------------------------------------
// Bike posts (r/xbiking, forums, Instagram): a suggested post title and a parts list
// grouped by section. Unlike `generateMarkup` (a PCPartPicker-style price table), these
// describe the bike as it is — your notes, what you paid, condition — and only include
// what the options allow, so the text never says more than the bike link does.
// ---------------------------------------------------------------------------

export type PostFormat = 'markdown' | 'plain' | 'bbcode'

export const POST_FORMATS: { id: PostFormat; label: string }[] = [
  { id: 'markdown', label: 'Reddit (Markdown)' },
  { id: 'plain', label: 'Plain text' },
  { id: 'bbcode', label: 'BBCode' },
]

export interface PostOptions {
  /** Public bike link for the last line. Omit for no link. */
  link?: string
  /** Per-part claimed weight. */
  weights: boolean
  pricesPaid: boolean
  notes: boolean
  condition: boolean
  /** Summary line: total weight, plus total paid when prices are on. */
  totals: boolean
  odometer: boolean
  /** Odometer display unit. Default 'mi'. */
  distanceUnit?: DistanceUnit
}

export const DEFAULT_POST_OPTIONS: PostOptions = {
  weights: false, pricesPaid: false, notes: true, condition: false, totals: true, odometer: false,
}

const WHEEL_LABELS: Record<WheelSize, string> = { 622: '700c', 584: '650b', 559: '26"', 507: '24"', 406: '20"' }

/** Resolved parts by slot (live catalog data, like the builder shows). */
function partsBySlot(build: Build): Partial<Record<PartCategory, Part>> {
  const out: Partial<Record<PartCategory, Part>> = {}
  for (const row of getSlotRows(build, undefined, true)) out[row.category] ??= row.part
  return out
}

function frameLabel(frame: Part): string {
  const title = partTitle(frame).replace(/\s+(frame ?set|frame & fork|frame)$/i, '').trim() || partTitle(frame)
  // Model year only means something for vintage frames; catalog years on current frames are release years.
  const year = frame.discontinued && frame.year && !title.includes(String(frame.year)) ? `${frame.year} ` : ''
  return year + title
}

function barsPhrase(bars: Part | undefined): string | undefined {
  if (!bars) return undefined
  const name = bars.name.replace(/\s*\([^)]*\)/g, '').replace(/\s*(handle)?bars?$/i, '').trim()
  return `${name || partTitle(bars)} bars`
}

const MOUNT_WORDS: Partial<Record<string, string>> = { 'Bar-End': 'bar-end', Downtube: 'downtube', Thumb: 'thumb', Stem: 'stem', Twist: 'twist' }

function drivetrainPhrase(p: Partial<Record<PartCategory, Part>>): string | undefined {
  const shifter = p.shifters?.attrs
  const system = shifter?.shiftSystem ?? p.rearDerailleur?.attrs?.shiftSystem
  if (system === 'Single Speed' || (p.sprocket && !p.rearDerailleur && !p.cassette)) {
    // A track cog threads onto a fixed hub; anything else is a freewheel.
    return p.sprocket?.attrs?.freehub === 'Track Fixed' ? 'fixed gear' : 'singlespeed'
  }
  const speeds = p.rearDerailleur?.attrs?.speeds ?? p.cassette?.attrs?.speeds ?? shifter?.speeds
  const rings = p.crankset?.attrs?.chainringCount
  const gearing = speeds && speeds > 1 ? (rings ? `${rings}x${speeds}` : `${speeds}-speed`) : undefined
  const mount = shifter?.shifterMount ? MOUNT_WORDS[shifter.shifterMount] : undefined
  if (system === 'Friction') return [gearing, mount, 'friction'].filter(Boolean).join(' ')
  // "Shimano GRX 11s" → "Shimano GRX": the compat family minus the generic bits.
  const group = system?.replace(/\b(Road|MTB|Mech|\d+(-\d+)?(\/\d+)?s)\b/g, '').replace(/\s+/g, ' ').trim()
  const bits = [group, gearing, mount && `${mount} shifters`].filter(Boolean)
  return gearing || mount ? bits.join(' ') : undefined
}

function wheelPhrase(p: Partial<Record<PartCategory, Part>>): string | undefined {
  const size = p.tires?.attrs?.wheelSize ?? p.wheels?.attrs?.wheelSize ?? p.rearWheel?.attrs?.wheelSize ?? p.rim?.attrs?.wheelSize
  if (!size || !WHEEL_LABELS[size]) return undefined
  const label = WHEEL_LABELS[size]
  const frameSizes = p.frame?.attrs?.wheelSizes
  if (frameSizes?.length && !frameSizes.includes(size)) return `${label} conversion`
  const w = p.tires?.attrs?.tireWidthMm
  if (!w) return size === 622 ? undefined : `${label} wheels`
  // MTB-width tires are sized in inches ("29 x 2.4"), road/gravel in mm ("700x43").
  const inches = `${(Math.round((w / 25.4) * 20) / 20).toFixed(2).replace(/\.?0+$/, '')}"`
  if (size === 622) return w >= 50 ? `29 x ${inches} tires` : `700x${w} tires`
  if (size === 584) return w >= 52 ? `27.5 x ${inches} tires` : `650b x ${w} tires`
  return `${label} x ${inches} tires`
}

/**
 * xbiking-style post title: "[1992 Bridgestone XO-1] Albatross bars, bar-end friction,
 * 650b conversion" — the frame in brackets, then up to three notable things the parts list
 * actually supports (bars, drivetrain, wheel size). Falls back to the bike name.
 */
export function suggestTitle(build: Build, maxLength = 110): string {
  const p = partsBySlot(build)
  const head = `[${p.frame ? frameLabel(p.frame) : build.name}]`
  const notable = [barsPhrase(p.handlebars), drivetrainPhrase(p), wheelPhrase(p)].filter((x): x is string => !!x)
  while (notable.length > 1 && `${head} ${notable.join(', ')}`.length > maxLength) notable.pop()
  if (notable.length) return `${head} ${notable.join(', ')}`
  return p.frame && !head.toLowerCase().includes(build.name.toLowerCase()) ? `${head} ${build.name}` : head
}

/** $80, $12.50, free — paid prices read better without ".00". */
const paidLabel = (n: number) => (n === 0 ? 'free' : formatPrice(n).replace(/\.00$/, ''))

interface PostLine {
  /** Slot label ("Frame"); empty for extras. */
  label: string
  name: string
  /** Parenthetical bits: paid, condition, weight. */
  meta: string[]
  note?: string
  url?: string
}

interface PostSection { title: string; lines: PostLine[] }

const oneLine = (s: string) => s.replace(/\s+/g, ' ').trim()

function postSections(build: Build, opts: PostOptions): PostSection[] {
  const groups = new Map<string, PostLine[]>()
  for (const row of getSlotRows(build, undefined, true)) {
    const part = row.part!
    const t = row.slot.tracking
    const qty = row.quantity > 1 && row.quantity !== defaultQuantity(row.category) ? `${row.quantity} × ` : ''
    const meta: string[] = []
    if (row.slot.status === 'wanted') meta.push('planned')
    if (opts.pricesPaid && t?.pricePaid != null) meta.push(paidLabel(t.pricePaid))
    if (opts.condition && t?.condition) meta.push(t.condition === 'nos' ? 'NOS' : conditionLabel(t.condition).toLowerCase())
    if (opts.weights && row.weightG != null) meta.push(formatWeight(row.weightG))
    const note = opts.notes && t?.notes?.trim() ? oneLine(t.notes) : undefined
    const group = getCategoryMeta(row.category)?.group ?? 'Other'
    const list = groups.get(group) ?? []
    list.push({ label: row.label, name: qty + partTitle(part), meta, note })
    groups.set(group, list)
  }
  const sections: PostSection[] = [...CATEGORY_GROUPS, 'Other']
    .filter((g) => groups.has(g))
    .map((g) => ({ title: g, lines: groups.get(g)! }))
  const extras = build.additionalItems ?? []
  if (extras.length) {
    sections.push({
      title: 'Extras',
      lines: extras.map((x) => ({
        label: '',
        name: x.name,
        meta: opts.pricesPaid && x.price != null ? [paidLabel(x.price)] : [],
        note: opts.notes && x.notes?.trim() ? oneLine(x.notes) : undefined,
        url: x.url,
      })),
    })
  }
  return sections
}

/** "Est. weight: 10.42 kg · Total paid: $1,170 · Odometer: 3,853 mi", or '' when nothing applies. */
function postSummary(build: Build, opts: PostOptions): string {
  const bits: string[] = []
  if (opts.totals) {
    const label = weightLabel(computeCompat(build))
    if (label !== '—') bits.push(`Est. weight: ${label}`)
    if (opts.pricesPaid) {
      const filled = build.components.filter((s) => s.part)
      const paid = filled.filter((s) => s.tracking?.pricePaid != null)
      if (paid.length) {
        const sum = paid.reduce((n, s) => n + s.tracking!.pricePaid!, 0)
        const missing = filled.length - paid.length
        bits.push(`Total paid: ${formatPrice(Math.round(sum * 100) / 100).replace(/\.00$/, '')}${missing ? ` (${missing} part${missing === 1 ? '' : 's'} not counted)` : ''}`)
      }
    }
  }
  if (opts.odometer && build.odometerKm) bits.push(`Odometer: ${formatDistance(build.odometerKm, opts.distanceUnit ?? 'mi')}`)
  return bits.join(' · ')
}

function paragraphs(text: string | undefined): string[] {
  return (text ?? '').split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean)
}

/** Backslash-escape characters Reddit's Markdown would act on, and line-leading list/heading markers. */
export function escapeMarkdown(s: string): string {
  return s
    .replace(/([\\`*_[\]~^>#|<])/g, '\\$1')
    .replace(/^(\s*)([-+])(\s)/gm, '$1\\$2$3')
    .replace(/^(\s*\d+)\.(\s)/gm, '$1\\.$2')
}

/** "Name (paid, condition, weight) — note", with `name` pre-rendered (links) and `esc` for user text. */
const withMeta = (l: PostLine, name: string, esc: (s: string) => string = (s) => s) =>
  `${name}${l.meta.length ? ` (${esc(l.meta.join(', '))})` : ''}${l.note ? ` — ${esc(l.note)}` : ''}`

/** Reddit Markdown: bold name, description, one bulleted list per section, summary, link. */
export function redditMarkdown(build: Build, opts: PostOptions): string {
  const md = escapeMarkdown
  const out: string[] = [`**${md(oneLine(build.name))}**`]
  for (const p of paragraphs(build.description)) out.push(md(oneLine(p)))
  for (const s of postSections(build, opts)) {
    out.push(`**${s.title}**`)
    out.push(s.lines.map((l) => {
      const name = l.url ? `[${md(l.name)}](${l.url})` : md(l.name)
      return `* ${l.label ? `**${md(l.label)}:** ` : ''}${withMeta(l, name, md)}`
    }).join('\n'))
  }
  const summary = postSummary(build, opts)
  if (summary) out.push(md(summary))
  if (opts.link) out.push(`[Full build & specs](${opts.link})`)
  return out.join('\n\n')
}

/** Plain text for rich-text editors, Instagram and chat: "Frame: …" lines under CAPS headings. */
export function plainTextPost(build: Build, opts: PostOptions): string {
  const out: string[] = [[oneLine(build.name), ...paragraphs(build.description)].join('\n')]
  for (const s of postSections(build, opts)) {
    out.push([s.title.toUpperCase(), ...s.lines.map((l) => (l.label ? `${l.label}: ` : '') + withMeta(l, l.name))].join('\n'))
  }
  const summary = postSummary(build, opts)
  if (summary) out.push(summary)
  if (opts.link) out.push(`Full build & specs: ${opts.link}`)
  return out.map((block) => block.replace(/[ \t]+$/gm, '')).join('\n\n')
}

/** BBCode for phpBB / XenForo / vBulletin bike forums. */
export function bbcodePost(build: Build, opts: PostOptions): string {
  const out: string[] = [[`[b]${oneLine(build.name)}[/b]`, ...paragraphs(build.description)].join('\n')]
  for (const s of postSections(build, opts)) {
    const items = s.lines.map((l) => {
      const name = l.url ? `[url=${l.url}]${l.name}[/url]` : l.name
      return `[*]${l.label ? `[b]${l.label}:[/b] ` : ''}${withMeta(l, name)}`
    })
    out.push([`[b]${s.title}[/b]`, '[list]', ...items, '[/list]'].join('\n'))
  }
  const summary = postSummary(build, opts)
  if (summary) out.push(summary)
  if (opts.link) out.push(`[url=${opts.link}]Full build & specs[/url]`)
  return out.join('\n\n')
}

export function generatePost(build: Build, format: PostFormat, opts: PostOptions): string {
  if (format === 'markdown') return redditMarkdown(build, opts)
  if (format === 'bbcode') return bbcodePost(build, opts)
  return plainTextPost(build, opts)
}
